# ═══════════════════════════════════════════════════════
#  自訂族群管理
# ═══════════════════════════════════════════════════════

def _custom_sectors_path() -> Path:
    return settings.ohlcv_path / "custom_sectors.json"


def _load_custom_sectors() -> dict[str, list[str]]:
    path = _custom_sectors_path()
    if path.exists():
        try:
            with open(path) as f:
                return json.load(f)
        except Exception:
            return {}
    return {}


def _save_custom_sectors(data: dict[str, list[str]]):
    path = _custom_sectors_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


