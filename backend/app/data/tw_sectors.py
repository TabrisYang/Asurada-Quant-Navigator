def get_sector_symbols(name: str) -> Optional[list[str]]:
    """查表取得族群代碼清單。支援別名 + 模糊匹配。"""
    key = name.strip()

    # 1) 精確匹配內建表
    if key in TW_SECTORS:
        return TW_SECTORS[key]

    # 2) 別名匹配（小寫）
    alias_key = key.lower()
    if alias_key in SECTOR_ALIASES:
        sector_name = SECTOR_ALIASES[alias_key]
        return TW_SECTORS.get(sector_name)

    # 3) 自訂族群
    custom = _load_custom_sectors()
    if key in custom:
        return custom[key]

    # 4) 模糊匹配（族群名包含 key 或 key 包含族群名）
    for sector_name, symbols in TW_SECTORS.items():
        if key in sector_name or sector_name in key:
            return symbols

    return None


def get_sector_name(name: str) -> Optional[str]:
    """回傳正式族群名稱（解析別名）。"""
    key = name.strip()
    if key in TW_SECTORS:
        return key
    alias_key = key.lower()
    if alias_key in SECTOR_ALIASES:
        return SECTOR_ALIASES[alias_key]
    custom = _load_custom_sectors()
    if key in custom:
        return key
    for sector_name in TW_SECTORS:
        if key in sector_name or sector_name in key:
            return sector_name
    return None


def list_sectors() -> list[dict]:
    """列出所有可用族群（內建 + 自訂）。"""
    result = []
    for name, symbols in TW_SECTORS.items():
        result.append({
            "name": name,
            "count": len(symbols),
            "source": "builtin",
        })
    for name, symbols in _load_custom_sectors().items():
        result.append({
            "name": name,
            "count": len(symbols),
            "source": "custom",
        })
    return result


def add_custom_sector(name: str, symbols: list[str]) -> dict:
    """新增或更新自訂族群。"""
    custom = _load_custom_sectors()
    custom[name] = symbols
    _save_custom_sectors(custom)
    return {"status": "success", "name": name, "count": len(symbols)}


def remove_custom_sector(name: str) -> dict:
    """移除自訂族群。"""
    custom = _load_custom_sectors()
    if name in custom:
        del custom[name]
        _save_custom_sectors(custom)
        return {"status": "success", "removed": name}
    return {"status": "not_found", "name": name}


def get_stock_name(code: str) -> str:
    """取得股票簡稱，不存在則回傳代碼本身。"""
    return TW_STOCK_NAMES.get(code, code)
